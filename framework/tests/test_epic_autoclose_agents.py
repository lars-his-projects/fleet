"""The close line of an epic counts also in a comment of a login of `agents` (#39): the runs of a repository can post
as a login that is not an owner."""
import agent_config
import epic_autoclose

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
CHECK = "Epic check: all criteria are met.\n\nClose this epic when #35 merges."


def comment(login):
    return {"body": CHECK + FOOTER, "user": {"login": login, "type": "User"}}


def test_agents_adds_the_logins_of_agents_to_the_owners():
    config = {"owner": "Boss", "agents": ["runner"]}
    assert agent_config.agents(config) == ["Boss", "runner"]
    assert agent_config.agents({"owner": "Boss"}) == ["Boss"]


def test_a_close_line_of_an_agent_login_counts(monkeypatch):
    monkeypatch.setattr(agent_config, "CONFIG", {"owner": "Boss", "agents": ["runner"]})
    assert epic_autoclose.line_of(comment("runner")) == 35
    assert epic_autoclose.line_of(comment("Boss")) == 35


def test_a_close_line_of_another_login_does_not_count(monkeypatch):
    monkeypatch.setattr(agent_config, "CONFIG", {"owner": "Boss", "agents": ["runner"]})
    assert epic_autoclose.line_of(comment("stranger")) is None
